use App\Repository\ProduitRepository;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;
use Symfony\Component\Validator\Constraints as Assert;

#[ORM\Entity(repositoryClass: ProduitRepository::class)]

class Produit
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private ?int $id = null;

    #[ORM\Column(length: 50)]
    #[Assert\NotBlank(message: "Le nom du produit est requis.")]
    #[Assert\Length(
        min: 2,
        max: 50,
        minMessage: "Le nom doit contenir au moins {{ limit }} caractères.",
        maxMessage: "Le nom ne peut pas dépasser {{ limit }} caractères."
    )]
    private ?string $nom = null;

    #[ORM\Column(length: 150)]
    #[Assert\NotBlank(message: "La description est requise.")]
    #[Assert\Length(
        min: 2,
        max: 150,
        minMessage: "La description doit contenir au moins {{ limit }} caractères.",
        maxMessage: "La description ne peut pas dépasser {{ limit }} caractères."
    )]
    private ?string $description = null;

    #[ORM\Column]
    #[Assert\NotNull(message: "Le prix est requis.")]
    #[Assert\Positive(message: "Le prix doit être un nombre positif.")]
    private ?float $prix = null;

    #[ORM\Column]
    #[Assert\NotNull(message: "La quantité en stock est requise.")]
    #[Assert\PositiveOrZero(message: "La quantité en stock doit être un nombre positif ou nul.")]
    private ?int $qtte_stock = null;
    

    #[ORM\Column]
    #[Assert\NotNull(message: "La quantité minimale est requise.")]
    #[Assert\Positive(message: "La quantité minimale doit être un nombre strictement positif.")]
    private ?int $Qtte_seuil_min = null;

    #[ORM\ManyToOne(targetEntity:Categorie::class, inversedBy:"produits", cascade:["persist"])]
    #[ORM\JoinColumn(name:'idCategorie', referencedColumnName:'idCategorie')]
    private $idCategorie;
    
    #[ORM\OneToMany(mappedBy: 'produit', targetEntity: CommandeDetail::class)]
    private Collection $commandeDetails;



    public function __construct()
    {
        $this->id_categorie = new ArrayCollection();
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function getId(): ?int
    {
        return $this->id;
    }

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function getNom(): ?string
    {
        return $this->nom;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function setNom(string $Nom): static
    {
        $this->nom = $Nom;

        return $this;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function getDescription(): ?string
    {
        return $this->description;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function setDescription(string $Description): static
    {
        $this->description = $Description;

        return $this;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function getPrix(): ?float
    {
        return $this->prix;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function setPrix(float $prix): static
    {
        $this->prix = $prix;

        return $this;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function getQtteStock(): ?int
    {
        return $this->qtte_stock;
    }
        public function getQtte_Stock(): ?int
    {
        return $this->qtte_stock;
    }
    
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function setQtteStock(int $qtte_stock): static
    {
        $this->qtte_stock = $qtte_stock;

        return $this;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function getQtteSeuilMin(): ?int
    {
        return $this->Qtte_seuil_min;
    }
        public function getQtte_Seuil_Min(): ?int
    {
        return $this->Qtte_seuil_min;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public function setQtteSeuilMin(int $Qtte_seuil_min): static
    {
        $this->Qtte_seuil_min = $Qtte_seuil_min;

        return $this;
    }
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
public function setIdCategorie(?Categorie $idCategorie): static
{
    $this->idCategorie = $idCategorie;
    return $this;
}

    public function getIdCategorie(): ?Categorie
    {
        return $this->idCategorie;
    }
}
